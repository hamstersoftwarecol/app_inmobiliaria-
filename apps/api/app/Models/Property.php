<?php

namespace App\Models;

use App\Domain\Listings\Enums\ListingType;
use App\Domain\Listings\Enums\PropertySource;
use App\Domain\Mls\Enums\ListingStatus;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * A listing shown by the platform: either agency-owned (internal) or
 * materialized from an MLS record. `location` (geography) is generated by
 * PostgreSQL from latitude/longitude. Publication and source fields are
 * never mass-assigned.
 */
#[Fillable([
    'listing_agent_id', 'property_type_id', 'property_subtype', 'listing_type', 'status', 'title',
    'description', 'description_es', 'list_price', 'street_address', 'unit', 'city', 'county', 'state',
    'postal_code', 'address_display', 'latitude', 'longitude', 'bedrooms', 'bathrooms', 'living_area_sqft',
    'lot_size_sqft', 'year_built', 'parking_spaces', 'garage_spaces', 'heating', 'cooling', 'amenities',
    'hoa_fee_monthly', 'annual_taxes',
])]
#[Hidden(['location'])]
class Property extends Model
{
    use HasFactory, SoftDeletes;

    /** @var array<string, mixed> */
    protected $attributes = [
        'source' => 'internal',
        'listing_type' => 'sale',
        'status' => 'active',
        'is_published' => false,
        'currency' => 'USD',
        'state' => 'NJ',
        'address_display' => true,
    ];

    protected function casts(): array
    {
        return [
            'source' => PropertySource::class,
            'listing_type' => ListingType::class,
            'status' => ListingStatus::class,
            'is_published' => 'boolean',
            'published_at' => 'datetime',
            'address_display' => 'boolean',
            'list_price' => 'decimal:2',
            'bathrooms' => 'decimal:1',
            'lot_size_sqft' => 'decimal:2',
            'hoa_fee_monthly' => 'decimal:2',
            'annual_taxes' => 'decimal:2',
            'latitude' => 'float',
            'longitude' => 'float',
            'heating' => 'array',
            'cooling' => 'array',
            'amenities' => 'array',
        ];
    }

    /**
     * @return BelongsTo<Agency, $this>
     */
    public function agency(): BelongsTo
    {
        return $this->belongsTo(Agency::class);
    }

    /**
     * @return BelongsTo<Agent, $this>
     */
    public function listingAgent(): BelongsTo
    {
        return $this->belongsTo(Agent::class, 'listing_agent_id');
    }

    /**
     * @return BelongsTo<PropertyType, $this>
     */
    public function propertyType(): BelongsTo
    {
        return $this->belongsTo(PropertyType::class);
    }

    /**
     * @return BelongsTo<MlsListing, $this>
     */
    public function mlsListing(): BelongsTo
    {
        return $this->belongsTo(MlsListing::class);
    }

    /**
     * @return HasMany<PropertyMedia, $this>
     */
    public function media(): HasMany
    {
        return $this->hasMany(PropertyMedia::class)->orderBy('sort_order')->orderBy('id');
    }

    /**
     * @return HasMany<PropertyStatusHistory, $this>
     */
    public function statusHistory(): HasMany
    {
        return $this->hasMany(PropertyStatusHistory::class)->latest('changed_at')->latest('id');
    }

    public function isMls(): bool
    {
        return $this->source === PropertySource::Mls;
    }

    /**
     * @param  Builder<Property>  $query
     */
    public function scopePublished(Builder $query): void
    {
        $query->where($this->qualifyColumn('is_published'), true);
    }

    /**
     * Published listings the given channel may show. For MLS listings the
     * provider's current display rules are re-checked at query time, so
     * revoking a permission hides listings immediately, before any resync.
     *
     * @param  Builder<Property>  $query
     */
    public function scopePubliclyVisible(Builder $query, string $channel = 'web'): void
    {
        $query->where($this->qualifyColumn('is_published'), true)
            ->where(fn (Builder $q) => $q
                ->where($this->qualifyColumn('source'), PropertySource::Internal->value)
                ->orWhereHas('mlsListing', fn (Builder $l) => $l
                    ->whereNull('removed_at')
                    ->where('internet_display_allowed', true)
                    ->whereHas('provider', fn (Builder $p) => $p
                        ->where('is_enabled', true)
                        ->whereHas('displayRule', fn (Builder $r) => $r
                            ->where('allow_public_display', true)
                            ->when($channel === 'mobile', fn (Builder $r) => $r->where('allow_mobile_display', true))))));
    }
}
